const HEAVY = ['tired', 'sad', 'anxious', 'angry', 'lonely', 'empty']

export function journalReply(emotion, level) {
  const pair = REPLIES[emotion] || REPLIES.empty
  return {
    text: pair[level >= 4 ? 1 : 0],
    // 힘든 감정을 크게 느낄 때는 다음에 할 수 있는 곳을 조용히 알려 준다
    offer: HEAVY.includes(emotion) && level >= 4,
  }
}

// 마음 대화 첫인사 (시간에 맞춰)
export function chatHello() {
  const h = new Date().getHours()
  if (h < 5 || h >= 23) return '늦은 시간까지 깨어 있군요. 잠이 오지 않는 밤이에요? 편하게 이야기해 주세요.'
  if (h < 11) return '좋은 아침이에요. 오늘 하루를 시작하는 마음은 어때요?'
  if (h < 18) return '안녕하세요, 마음곁이에요. 오늘 어떤 이야기를 나누고 싶나요?'
  return '오늘 하루 어땠어요? 무슨 이야기든 편하게 들려주세요.'
}
