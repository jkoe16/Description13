// 들를 때마다 같은 순서만 보지 않도록, 흐름(묶음 순서)은 지키면서 묶음 안의 순서만 섞는다.
// 맨 처음 한 마디("괜찮아. 여기선 울어도 돼.")는 늘 같은 자리에서 맞이한다.
export function wordOrder(rand = Math.random) {
  const shuffle = (list) => {
    const a = [...list]
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1))
      ;[a[i], a[j]] = [a[j], a[i]]
    }
    return a
  }
  const [first, ...rest] = WORD_GROUPS[0]
  return [first, ...shuffle(rest), ...WORD_GROUPS.slice(1).flatMap(shuffle)]
}
